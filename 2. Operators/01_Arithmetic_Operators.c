#include <stdio.h>

int main ()
{
    int x=10;
    int y=5;
//addition
    printf("%d\n", x+y);
//subtraction
    printf("%d\n", x-y);
//multiplication
    printf("%d\n", x*y);
//division
    printf("%d\n", x/y);
//modulus
    printf("%d\n", x%y);

int z=6;
//increment
    ++z;
    printf("%d\n", z);
//decrement
    --z;
    printf("%d\n", z);
    
return 0;
}
